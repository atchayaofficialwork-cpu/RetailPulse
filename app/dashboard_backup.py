
import streamlit as st
import pandas as pd
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
DATA_DIR = BASE_DIR / "data" / "processed"
REPORT_DIR = BASE_DIR / "reports"

DATA_PATH = DATA_DIR / "ecommerce_cleaned.csv"
SEGMENT_PATH = DATA_DIR / "customer_segments.csv"
FORECAST_PATH = DATA_DIR / "demand_forecast_next_3_months.csv"
INVENTORY_PATH = DATA_DIR / "inventory_recommendations.csv"
CHURN_REPORT_PATH = REPORT_DIR / "churn_customer_report.txt"

st.set_page_config(
    page_title="RetailPulse Analytics",
    page_icon="📊",
    layout="wide"
)


@st.cache_data
def load_data():
    df = pd.read_csv(DATA_PATH)
    df["Purchase Date"] = pd.to_datetime(
        df["Purchase Date"], errors="coerce"
    )
    return df


def load_csv(path):
    if not path.exists():
        return None
    try:
        return pd.read_csv(path)
    except Exception as exc:
        st.warning(f"Could not read {path.name}: {exc}")
        return None


def show_missing_file(path, command):
    st.warning(f"Required output not found: {path.name}")
    st.code(command)


st.title("RetailPulse")
st.caption("AI-Powered Customer Analytics & Demand Forecasting Platform")

try:
    df = load_data()
except Exception as exc:
    st.error(f"Could not load cleaned dataset: {exc}")
    st.stop()

required_columns = [
    "Customer ID", "Purchase Date", "Product Category",
    "Product Price", "Quantity", "Total Purchase Amount",
    "Payment Method", "Customer Age", "Churn"
]

missing_columns = [c for c in required_columns if c not in df.columns]
if missing_columns:
    st.error(f"Dataset is missing columns: {', '.join(missing_columns)}")
    st.stop()

st.sidebar.title("RetailPulse Navigation")
page = st.sidebar.radio(
    "Select Module",
    [
        "Sales Analysis",
        "Customer Segments",
        "Demand Forecast",
        "Churn Analysis",
        "Inventory Insights"
    ]
)

st.sidebar.divider()
st.sidebar.caption(f"Dataset records: {len(df):,}")
st.sidebar.caption(f"Unique customers: {df['Customer ID'].nunique():,}")


# --------------------------------------------------
# 1. SALES ANALYSIS
# --------------------------------------------------
if page == "Sales Analysis":
    st.header("Sales Analysis")

    total_sales = df["Total Purchase Amount"].sum()
    transactions = len(df)
    average_purchase = df["Total Purchase Amount"].mean()
    categories = df["Product Category"].nunique()

    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Total Purchase Amount", f"{total_sales:,.2f}")
    c2.metric("Transactions", f"{transactions:,}")
    c3.metric("Average Purchase", f"{average_purchase:,.2f}")
    c4.metric("Product Categories", categories)

    left, right = st.columns(2)

    with left:
        st.subheader("Sales by Product Category")
        category_sales = (
            df.groupby("Product Category")["Total Purchase Amount"]
            .sum()
            .sort_values(ascending=False)
        )
        st.bar_chart(category_sales)

    with right:
        st.subheader("Payment Methods")
        st.bar_chart(df["Payment Method"].value_counts())

    st.subheader("Monthly Sales Trend")
    monthly_sales = (
        df.dropna(subset=["Purchase Date"])
        .set_index("Purchase Date")
        .resample("ME")["Total Purchase Amount"]
        .sum()
    )
    st.line_chart(monthly_sales)

    st.subheader("Category Sales Details")
    st.dataframe(
        category_sales.rename("Total Sales").reset_index(),
        width="stretch",
        hide_index=True
    )


# --------------------------------------------------
# 2. CUSTOMER SEGMENTS
# --------------------------------------------------
elif page == "Customer Segments":
    st.header("Customer Segmentation")
    st.write("Customer groups generated by the K-Means segmentation model.")

    segments = load_csv(SEGMENT_PATH)

    if segments is None:
        show_missing_file(
            SEGMENT_PATH,
            "python -u .\\src\\customer_segmentation.py"
        )
    else:
        st.metric("Customers in Segmentation Output", f"{len(segments):,}")

        segment_column = next(
            (
                c for c in ["Segment", "Customer_Segment",
                            "Customer Segment", "Cluster"]
                if c in segments.columns
            ),
            None
        )

        if segment_column:
            segment_counts = (
                segments[segment_column]
                .fillna("Unknown")
                .astype(str)
                .value_counts()
            )

            st.subheader("Customers by Segment")
            st.bar_chart(segment_counts)

            st.dataframe(
                segment_counts.rename("Customer Count").reset_index()
                .rename(columns={"index": segment_column}),
                width="stretch",
                hide_index=True
            )
        else:
            st.info(
                "The segmentation file does not contain a recognized "
                "segment or cluster column. Showing its available columns."
            )

        st.subheader("Segmentation Results")
        st.dataframe(segments.head(500), width="stretch", hide_index=True)

        st.caption(
            "K-Means groups customers using the features configured in "
            "the segmentation script. Segment names depend on that script."
        )


# --------------------------------------------------
# 3. DEMAND FORECAST
# --------------------------------------------------
elif page == "Demand Forecast":
    st.header("Demand Forecast")
    st.caption("Model output and historical demand")

    forecast = load_csv(FORECAST_PATH)

    if forecast is None:
        show_missing_file(
            FORECAST_PATH,
            "python -u .\\src\\demand_forecasting.py"
        )
    else:
        needed = {"Month", "Product Category", "Forecast_Demand"}

        if not needed.issubset(forecast.columns):
            st.error(
                "Forecast file has unexpected columns. "
                f"Available columns: {', '.join(forecast.columns)}"
            )
        else:
            forecast["Month"] = pd.to_datetime(
                forecast["Month"], errors="coerce"
            )
            forecast["Forecast_Demand"] = pd.to_numeric(
                forecast["Forecast_Demand"], errors="coerce"
            )
            forecast = forecast.dropna(
                subset=["Month", "Product Category", "Forecast_Demand"]
            )

            st.warning(
                "Historical demonstration only: the training data ends "
                "in September 2023. These forecasts are for October–"
                "December 2023 and are not current 2026 predictions."
            )

            if not forecast.empty:
                c1, c2, c3 = st.columns(3)
                c1.metric("Forecast Records", f"{len(forecast):,}")
                c2.metric(
                    "Categories",
                    forecast["Product Category"].nunique()
                )
                c3.metric(
                    "Total Forecast Demand",
                    f"{forecast['Forecast_Demand'].sum():,.0f}"
                )

                st.subheader("Forecast by Month and Category")
                chart_data = forecast.pivot_table(
                    index="Month",
                    columns="Product Category",
                    values="Forecast_Demand",
                    aggfunc="sum"
                ).sort_index()
                st.line_chart(chart_data)

                st.subheader("Forecast Results")
                display_forecast = forecast.copy()
                display_forecast["Month"] = (
                    display_forecast["Month"].dt.strftime("%Y-%m")
                )
                st.dataframe(
                    display_forecast.sort_values(
                        ["Month", "Product Category"]
                    ),
                    width="stretch",
                    hide_index=True
                )

                st.download_button(
                    "Download Forecast CSV",
                    data=forecast.to_csv(index=False).encode("utf-8"),
                    file_name="retailpulse_demand_forecast.csv",
                    mime="text/csv"
                )

    st.subheader("Historical Daily Quantity")
    daily = (
        df.dropna(subset=["Purchase Date"])
        .set_index("Purchase Date")
        .resample("D")["Quantity"]
        .sum()
    )
    st.line_chart(daily)
    st.dataframe(
        daily.tail(30).rename("Quantity").reset_index(),
        width="stretch",
        hide_index=True
    )


# --------------------------------------------------
# 4. CHURN ANALYSIS
# --------------------------------------------------
elif page == "Churn Analysis":
    st.header("Customer Churn Analysis")

    churn_values = pd.to_numeric(df["Churn"], errors="coerce")
    valid_churn = churn_values.dropna()

    c1, c2, c3 = st.columns(3)
    c1.metric("Transaction Records", f"{len(df):,}")
    c2.metric("Records Labelled Churned", f"{int((valid_churn == 1).sum()):,}")
    c3.metric(
        "Record-Level Churn Label Rate",
        f"{(valid_churn == 1).mean() * 100:.2f}%"
        if not valid_churn.empty else "N/A"
    )

    st.subheader("Churn Label Distribution")
    st.bar_chart(valid_churn.value_counts().sort_index())

    st.warning(
        "The current customer-level churn model has ROC-AUC approximately "
        "0.50, which is close to random ranking. Do not use its predictions "
        "for business decisions until the churn label and features are "
        "validated and the model is improved."
    )

    st.caption(
        "These figures describe the dataset's existing labels. "
        "A labelled record is not automatically proof of future churn."
    )

    if CHURN_REPORT_PATH.exists():
        with st.expander("View Customer Churn Model Report"):
            st.text(CHURN_REPORT_PATH.read_text(encoding="utf-8"))
    else:
        st.info("Customer churn model report was not found.")


# --------------------------------------------------
# 5. INVENTORY INSIGHTS
# --------------------------------------------------
elif page == "Inventory Insights":
    st.header("Inventory Insights")
    st.write("Forecast-based category-level stock recommendations.")

    inventory = load_csv(INVENTORY_PATH)

    if inventory is None:
        show_missing_file(
            INVENTORY_PATH,
            "python -u .\\src\\inventory_recommendation.py"
        )
    else:
        expected = {
            "Product Category", "Current_Stock",
            "Recommended_Stock_Level", "Reorder_Quantity",
            "Recommendation"
        }

        if not expected.issubset(inventory.columns):
            st.error(
                "Inventory file has unexpected columns. "
                f"Available columns: {', '.join(inventory.columns)}"
            )
        else:
            reorder_total = pd.to_numeric(
                inventory["Reorder_Quantity"], errors="coerce"
            ).fillna(0).sum()

            reorder_categories = (
                pd.to_numeric(
                    inventory["Reorder_Quantity"], errors="coerce"
                ).fillna(0) > 0
            ).sum()

            c1, c2, c3 = st.columns(3)
            c1.metric("Categories", inventory["Product Category"].nunique())
            c2.metric("Total Reorder Quantity", f"{reorder_total:,.0f}")
            c3.metric("Categories to Reorder", int(reorder_categories))

            st.subheader("Reorder Quantity by Category")
            chart_inventory = inventory.set_index("Product Category")[
                "Reorder_Quantity"
            ]
            st.bar_chart(chart_inventory)

            st.subheader("Inventory Recommendation Table")
            st.dataframe(inventory, width="stretch", hide_index=True)

            st.download_button(
                "Download Inventory Recommendations",
                data=inventory.to_csv(index=False).encode("utf-8"),
                file_name="retailpulse_inventory_recommendations.csv",
                mime="text/csv"
            )

            st.info(
                "Recommendations use the stock values entered when the "
                "inventory script ran, with a one-month average-demand "
                "baseline and 20% safety-stock assumption. Update the "
                "stock inputs before using the results operationally."
            )


st.divider()
st.caption("RetailPulse | Data-driven retail insights")